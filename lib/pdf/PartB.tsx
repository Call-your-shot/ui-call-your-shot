  page: {
    fontFamily: font.family,
    padding: page.marginPt,
    paddingTop: 70,
    paddingBottom: 50,
    fontSize: font.body,
    color: color.body,
  },
  partTitle: { fontSize: 20, fontWeight: 700, color: color.ink, marginBottom: 4 },
